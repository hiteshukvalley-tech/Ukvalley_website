const b = await launch();
const p = await newPage(b, { width: 1280, height: 900 });
await go(p, "/careers");
const role = await p.$eval("#open-roles article h3", (e) => e.textContent.trim());
// click on the card's summary text (not the title) — the whole card should open the job
await p.$eval("#open-roles", (e) => e.scrollIntoView());
await sleep(1500);
const box = await (await p.$("#open-roles article p")).boundingBox();
await p.mouse.click(box.x + 20, box.y + 5);
