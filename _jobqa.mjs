check("clicking the card opens the job page", /\/careers\/[a-z0-9-]+$/.test(p.url()), p.url());
const t = await text(p);
check("title shown", t.includes(role));
for (const s of ["About the role", "What you'll do", "What we're looking for", "What you get", "Job overview", "Location", "Employment type", "Other open roles"]) check(`section: ${s}`, t.includes(s));
check("job-posting data present", (await p.$$eval('script[type="application/ld+json"]', (s) => s.map((x) => x.textContent).join(""))).includes('"JobPosting"'));
await p.screenshot({ path: ".shots/career-detail.png" });
await p.$$eval("aside button", (bs) => bs[0].click());
await p.waitForSelector("#apply-position", { timeout: 10000 });
